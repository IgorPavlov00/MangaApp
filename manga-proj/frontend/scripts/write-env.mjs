// Writes src/environments/environment.ts from environment variables (Netlify build settings)
// or from a local .env file. Runs automatically before `npm start`, `npm run build` and `npm test`.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const fromFile = {};
if (existsSync('.env')) {
  for (const line of readFileSync('.env', 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (match) fromFile[match[1]] = match[2].replace(/^["']|["']$/g, '');
  }
}
const get = (key, fallback = '') => process.env[key] ?? fromFile[key] ?? fallback;

const env = {
  supabaseUrl: get('SUPABASE_URL'),
  // The publishable ("anon") key is designed to be public; row level security protects the data.
  supabaseKey: get('SUPABASE_PUBLISHABLE_KEY', get('SUPABASE_ANON_KEY')),
  apiUrl: get('API_URL', 'http://localhost:8084').replace(/\/$/, ''),
};

mkdirSync('src/environments', { recursive: true });
writeFileSync(
  'src/environments/environment.ts',
  `// Generated by scripts/write-env.mjs. Do not edit; set environment variables or .env instead.\n` +
    `export const environment = ${JSON.stringify(env, null, 2)} as const;\n`,
);
console.log(
  `environment: api=${env.apiUrl}, supabase=${env.supabaseUrl || '(not configured)'}`,
);
